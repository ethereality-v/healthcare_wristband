"""Generate firmware/wristband/exercise_table.cpp from shared/exercises.json.

Run from the repository root after editing the exercise list:

    python tools/gen_exercise_table.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shared" / "exercises.json"
OUTPUT = ROOT / "firmware" / "wristband" / "exercise_table.cpp"

MODES = {"tilt": "DetectMode::Tilt", "motion": "DetectMode::Motion", "hold": "DetectMode::Hold"}
AXES = {"vertical": "MotionAxis::Vertical", "dominant": "MotionAxis::Dominant"}


def render(data: dict) -> str:
    rows = []
    for ex in data["exercises"]:
        if ex.get("tracker") != "wrist":
            continue
        rows.append(
            '    {{"{id}", "{unit}", {mode}, {axis}, {start:.1f}f, {top:.1f}f, {ret:.1f}f, '
            "{thr:.2f}f, {mn}, {mx}}},".format(
                id=ex["id"],
                unit=ex.get("unit", "reps"),
                mode=MODES[ex["mode"]],
                axis=AXES[ex.get("axis", "vertical")],
                start=ex.get("start_deg", 0),
                top=ex.get("top_deg", 0),
                ret=ex.get("return_deg", 0),
                thr=ex.get("threshold", 0),
                mn=ex.get("min_rep_ms", 0),
                mx=ex.get("max_rep_ms", 0),
            )
        )
    return (
        "// AUTO-GENERATED by tools/gen_exercise_table.py from shared/exercises.json.\n"
        "// Do not edit by hand: edit the JSON and re-run the script.\n"
        '#include "exercise_profile.h"\n'
        "#include <string.h>\n\n"
        "//  id, unit, mode, axis, startDeg, topDeg, returnDeg, threshold, minRepMs, maxRepMs\n"
        "const ExerciseProfile EXERCISES[] = {\n"
        + "\n".join(rows)
        + "\n};\n\n"
        "const int EXERCISE_COUNT = sizeof(EXERCISES) / sizeof(EXERCISES[0]);\n\n"
        "const ExerciseProfile* findExercise(const char* id) {\n"
        "    if (id == nullptr) return nullptr;\n"
        "    for (int i = 0; i < EXERCISE_COUNT; i++) {\n"
        "        if (strcmp(EXERCISES[i].id, id) == 0) return &EXERCISES[i];\n"
        "    }\n"
        "    return nullptr;\n"
        "}\n"
    )


def main() -> int:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    text = render(data)
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("exercise_table.cpp is out of date: run python tools/gen_exercise_table.py")
            return 1
        print("exercise_table.cpp is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
